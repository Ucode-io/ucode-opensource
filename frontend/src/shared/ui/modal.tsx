import type { ReactNode } from "react";
import { createPortal } from "react-dom";

/**
 * Модальное окно: подложка во весь экран, окно по центру, портал в <body>.
 *
 * Портал — суть этого компонента, а не деталь. Окно открывают откуда
 * угодно: из всплывашки в сайдбаре, из меню колонки, из карточки. У всех
 * у них свой z-index, а элемент с z-index создаёт КОНТЕКСТ НАЛОЖЕНИЯ:
 * потомки в нём считаются между собой и наружу не выходят, сколько им
 * ни поставь. Поэтому «Выйти из аккаунта?», открытое из меню профиля
 * (z-50), уезжало под карточку записи (z-50, но позже в DOM) — поднять
 * окно числом было нельзя в принципе.
 *
 * В <body> контекст один, общий, и число снова начинает работать: z-60
 * над карточкой, под уведомлениями (лестница — в app/styles.css).
 *
 * Escape здесь не слушается: у половины окон внутри свои поля и списки
 * со своим Escape, и общий обработчик закрывал бы окно вместе с ними.
 */
export function Modal({
  onClose,
  className = "grid place-items-center p-4",
  background = "var(--color-overlay)",
  children,
}: {
  /** Щелчок мимо окна. */
  onClose: () => void;
  /** Раскладка подложки. По умолчанию окно по центру экрана. */
  className?: string;
  /** Цвет подложки — токен темы. Просмотрщик файла берёт плотнее. */
  background?: string;
  children: ReactNode;
}) {
  return createPortal(
    <div
      /*
       * Метка для тех, кто закрывается по клику мимо себя. Портал уносит
       * окно из поддерева того, кто его открыл, и для всплывашки нажатие
       * на кнопку окна выглядит как «мимо»: она закрывалась, уносила
       * окно с собой, и click до кнопки не долетал. См. Popover.
       */
      data-modal
      className={`fixed inset-0 z-60 ${className}`}
      style={{ background }}
      /* Мимо — это подложка и только она: щелчок внутри окна всплывает
         до неё же, и без сравнения окно закрывалось бы от любого клика. */
      onPointerDown={(event) => event.target === event.currentTarget && onClose()}
    >
      {children}
    </div>,
    document.body,
  );
}
