import i18n from "@/shared/lib/i18n";
import type { UrlTemplate } from "./url-template";

/**
 * View — как показан набор строк: таблица, доска, календарь. Набор view
 * принадлежит пункту меню (GET /v3/menus/{menuId}/views), а не таблице:
 * два пункта могут показывать одну таблицу разными наборами view.
 */

/** Типы, которые отдаёт бэкенд. Рисуются те, что в IMPLEMENTED_VIEW_TYPES. */
export const VIEW_TYPES = [
  "TABLE",
  "BOARD",
  "CALENDAR",
  "GRID",
  "PIVOT",
  "SECTION",
  "TIMELINE",
  "TREE",
] as const;

export type ViewType = (typeof VIEW_TYPES)[number];

/**
 * SECTION — не вкладка. Это раскладка формы записи в Drawer: те же
 * columns, но описывают секции карточки, а не колонки таблицы.
 * Показать его вкладкой — значит предложить открыть таблицу, которой нет.
 */
const NOT_A_TAB = new Set<string>(["SECTION"]);

/** Экраны, которые действительно есть. Остальные вкладки видны, но пусты. */
export const IMPLEMENTED_VIEW_TYPES = new Set<string>([
  "TABLE",
  "TREE",
  "BOARD",
  "CALENDAR",
  "TIMELINE",
  "PIVOT",
]);

/**
 * Типы, которыми бывает ВКЛАДКА СВЯЗИ в карточке записи.
 *
 * Совпадает с IMPLEMENTED_VIEW_TYPES, но список свой не зря: два типа
 * во вкладке устроены иначе, чем на экране.
 *
 * У КАЛЕНДАРЯ период и видимый день живут в своём состоянии, а не
 * в адресе: адрес занят основной таблицей — той, из которой открыли
 * карточку. Цена та же, что у сортировки и страницы вкладки: ссылка
 * открывает её с текущего месяца.
 *
 * ТАЙМЛАЙН — по той же причине, что и календарь: масштаб и видимый
 * день у вкладки свои, а не в адресе.
 *
 * ДЕРЕВО собирается на клиенте. Ручка дерева
 * (`POST /v2/items/{slug}/tree`) читает из тела ровно ОДНО условие —
 * родителя (`<slug>_id`), — а всё остальное молча отбрасывает
 * (object_builder, storage/postgres/ag_grid_tree.go:105 и :203).
 * Отбор по колонке-ссылке до неё не доезжает, и дерево показало бы ВСЮ
 * чужую таблицу. Поэтому вкладка строит иерархию на клиенте, из строк,
 * которые и так загружены с нужным отбором (features/item/model/tree,
 * groupByParent). Старая админка фильтры в эту ручку шлёт и получает
 * то самое «всё» — см. docs/backend-notes.md.
 */
export const TAB_VIEW_TYPES = VIEW_TYPES.filter((type) => IMPLEMENTED_VIEW_TYPES.has(type));

export type View = {
  id: string;
  type: string;
  /** Таблица, из которой берутся строки. */
  tableSlug: string;
  /**
   * Имя вкладки на базовом языке. Пустое — обычное дело: у view, созданных
   * до появления имён, его нет, и вкладка называется своим типом.
   */
  name: string;
  /** То же имя по языкам ДАННЫХ (attributes.name_<short_name>). */
  names: Record<string, string>;
  /** Порядок вкладок задаёт админ. */
  order: number;
  /**
   * Размер страницы по умолчанию, заданный в настройках view. Свободное
   * число, а не выбор из списка, — поэтому переключатель размера умеет
   * показывать любое значение, а не только свои четыре.
   */
  defaultLimit: number | null;
  /**
   * View, встроенный во вкладку связи в Drawer. Своей вкладки на экране
   * таблицы у него нет.
   */
  isRelationView: boolean;
  /**
   * Таблица, строки которой показывает вкладка связи. У обычного view
   * пусто.
   *
   * Именно ею старая админка и связывает вкладку с таблицей: `relation_id`
   * у заведённых руками relation view пуст — форма создания его не шлёт
   * (useViewCreatePopupProps.jsx), — поэтому связь приходится искать
   * по этому слагу.
   */
  relationTableSlug: string;
  /**
   * Связь, к которой привязан view. Заполнена у тех, что завёл бэкенд
   * вместе со связью, и у наших: с ней вкладка находит свою связь
   * однозначно, а не по слагу таблицы.
   */
  relationId: string;
  /** Подпись таблицы из `relation_table_slug` — её подставляет бэкенд. */
  tableLabel: string;
  /**
   * Поля, по которым админ предложил фильтровать (attributes.quick_filters).
   * Здесь id — и у полей-связей это, как и в columns, id связи.
   *
   * Это начальный набор чипов в подшапке, а не ограничение: добавить
   * можно любое поле, и выбор уезжает в адрес, а не в настройки view.
   */
  quickFilterIds: string[];
  /**
   * Колонки в порядке показа.
   *
   * Здесь id — но не всегда id поля: у полей-связей view хранит id связи.
   * Разворачивается в resolveColumns, ни один компонент этого не знает.
   */
  columnIds: string[];
  /**
   * Слаги полей, показанных на полосе таймлайна, у view из старой
   * админки (`attributes.visible_field`). У всех остальных пусто.
   *
   * Запасной вариант для `columns`, а не вторая настройка: разбирается
   * в одном месте (resolveColumns), пишется всегда `columns`.
   */
  barFieldSlugs: string[];
  /**
   * Закреплённые колонки (attributes.fixedColumns). Не уезжают при
   * прокрутке вбок — в таблице на тридцать полей без этого не понять,
   * чья это строка.
   *
   * Ключи те же, что и в columns. В хранилище это объект
   * `{id: true}`, а не список: порядок закрепления значения не имеет,
   * важен порядок в columns — закреплённые всё равно рисуются слева.
   */
  fixedColumnIds: string[];
  /**
   * Отбор, с которым таблица открывается (attributes.default_filters).
   *
   * Карта «слаг → условие» — ровно то, что уходит в тело get-list.
   * Разбирается в фильтры один раз, в api; см. fromConditions.
   */
  defaultFilters: Record<string, unknown>;
  /**
   * Куда уводит щелчок по строке (`attributes.navigate`). Пустой адрес —
   * открывается карточка, как обычно.
   */
  navigate: UrlTemplate;
  /**
   * Куда ведёт «новая запись» (`attributes.url_object`). Пустой адрес —
   * строка заводится на месте, в таблице.
   */
  objectUrl: UrlTemplate;
  /** Адрес PDF записи (`attributes.pdf_url`). Пусто — кнопки нет. */
  pdfUrl: string;
  /**
   * Догружать строки прокруткой вместо номеров страниц
   * (`attributes.infinite_scroll`).
   *
   * Настройка view, а не человека: она про то, как читают этот список.
   * Журнал событий листают прокруткой, справочник — страницами, и
   * решает это тот, кто настроил экран, а не тот, кто на него зашёл.
   *
   * Выключено по умолчанию: у view, настроенных до появления флага,
   * страницы и были.
   */
  infiniteScroll: boolean;
  /**
   * Поля группировки (`attributes.group_by_columns`) в порядке уровней.
   * Ключи те же, что и в columns: у поля-связи это id связи. Пусто —
   * группировки нет.
   *
   * Уровней столько, сколько выбрано: настройка и в старой админке была
   * списком галочек (HeaderFilter/components/Group), а не выбором одного
   * поля.
   *
   * Не путать с `tabGroupId`: тот лежит в КОЛОНКЕ `group_fields` и значит
   * другое — раскладку (вкладки таблицы, колонки доски). Бэкенд эти два
   * ключа местами путает: серверная ветка группировки читает сначала
   * attributes, потом колонку (object_builder.go:2072), — но настройки
   * это разные, и панели у них в старой админке тоже разные.
   */
  groupByIds: string[];
  /**
   * Поле, по которому view РАСКЛАДЫВАЕТСЯ (`group_fields`, первый
   * элемент). Ключ тот же, что и в columns: у поля-связи это id связи.
   * Пусто — раскладки нет.
   *
   * Одно поле — две раскладки, и обе берут его отсюда: таблица делает
   * из значений вкладки и показывает по одному значению за раз, доска
   * — колонки и показывает их все сразу. Так же его читает и старая
   * админка (useBoardProps.jsx: `view.group_fields[0]`).
   *
   * Не путать с `groupByIds`: там строки собираются в группы внутри
   * одного списка, здесь — список сужается до одного значения, и
   * остальные строки на экран не приезжают вовсе.
   *
   * Колонка таблицы, а не ключ attributes: бэкенд пишет её отдельным
   * `group_fields = $N` при каждом PUT (view.go, Update).
   *
   * Один уровень намеренно: настройка хранит список, но и старая
   * админка кладёт туда ровно один элемент (useTabGroupProps.jsx).
   */
  tabGroupId: string;
  /**
   * Второй уровень раскладки ДОСКИ: её колонки разрезаются на дорожки
   * по значениям этого поля (`attributes.sub_group_by_id`). Ключ тот же,
   * что и у `tabGroupId`. Пусто — доска в одну дорожку.
   *
   * Только у доски: у таблицы вкладка одна на экран, и второго уровня
   * там просто некуда деть. В старой админке пункт «Sub group» тоже
   * показывается ровно при `view.type === "BOARD"`
   * (HeaderFilter/components/ViewOptions.jsx:296).
   */
  subGroupId: string;
  /**
   * Слаг поля, с которого начинается событие календаря и полоса
   * таймлайна (колонка `calendar_from_slug`). Пусто — рисовать нечего.
   *
   * Именно СЛАГ, а не id, в отличие от `columns` и `group_fields`: так
   * эту настройку хранит база, так её кладёт в тело get-list старая
   * админка. Читается из колонки таблицы — `attributes.calendar_from_slug`
   * не читается вовсе: старый фронт брал `view.calendar_from_slug ??
   * view.attributes.calendar_from_slug` в девяти местах, а пишет обе
   * половины бэкенд только в колонку (view.go, Update).
   */
  dateFromSlug: string;
  /** Слаг поля конца события (`calendar_to_slug`). Пусто — событие точкой. */
  dateToSlug: string;
  /**
   * Слаг поля, вариантами которого красятся события (`status_field_slug`).
   *
   * Только читается: ни одна ручка эту колонку не обновляет — в теле
   * PUT её нет (view.go, Update). См. docs/backend-notes.md.
   */
  statusFieldSlug: string;
  /**
   * Нерабочие дни: ЧУЖАЯ таблица и колонка дня в ней (`disable_dates`).
   * Пусто — нерабочих дней нет.
   *
   * Тоже только читается — по той же причине, что и `statusFieldSlug`.
   */
  disableDates: { tableSlug: string; daySlug: string } | null;
  /**
   * Режим, с которого календарь открывается (`attributes.period`):
   * MONTH, WEEK или DAY. Пусто — MONTH.
   *
   * Дальше режим живёт в адресе: переключение — это то, чем экраном
   * пользуются, а не то, что настраивает админ.
   */
  period: string;
  /**
   * View, как его отдал бэкенд. Нужен для записи: PUT перезаписывает
   * строку целиком, причём calendar_from_slug, calendar_to_slug,
   * group_fields и columns он проставляет ВСЕГДА, даже когда их не
   * прислали (view.go, Update). Собранное заново тело стёрло бы
   * настройки, которых мы не показываем.
   */
  raw: Record<string, unknown>;
};

/** Показывается ли view вкладкой на экране таблицы. */
export const isTabView = (view: View) => !view.isRelationView && !NOT_A_TAB.has(view.type);

/**
 * Имя view, как его задал админ. Пустая строка — имени нет вовсе.
 *
 * Локаль ИНТЕРФЕЙСА, потом язык ДАННЫХ, потом ЛЮБОЙ заданный, потом
 * колонка `name`. Имя вкладки — надпись интерфейса, и переключение
 * языка обязано её менять (старая админка писала и читала его как
 * `attributes.name_<локаль>`); но коды проекта с ru/en/uz совпадают
 * не всегда, поэтому за локалью идёт язык данных. Третья ступень
 * не для красоты: без неё view, названный только по-узбекски,
 * выглядел бы безымянным. Колонку `name` бэкенд заполняет далеко
 * не всегда, поэтому на неё одну надежды нет.
 */
export function viewName(view: View, language: string): string {
  return (
    view.names[i18n.language]?.trim() ||
    view.names[language]?.trim() ||
    Object.values(view.names)
      .map((name) => name.trim())
      .find(Boolean) ||
    view.name
  );
}
