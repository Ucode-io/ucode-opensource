/**
 * Схема таблицы: поля и связи. Это «что за колонки бывают», а не данные —
 * данные живут в фиче item. Разный жизненный цикл: схему меняет админ
 * в конструкторе, строки меняются постоянно.
 */

import i18n from "@/shared/lib/i18n";

/**
 * Типы полей, которые отдаёт бэкенд (field.proto, enum FieldType).
 * Список открытый сознательно: незнакомый тип рисуется как текст,
 * а не роняет таблицу.
 */
/**
 * Подписи по языкам. Ключ — short_name языка проекта
 * (GET /v1/company-project/{id} → language[].short_name), например
 * "en" и "cyr", — и он не обязан совпадать с локалью интерфейса
 * (ru/en/uz): набор кодов задаёт проект, локаль выбирает человек.
 *
 * Читаются обе оси, по порядку: см. localized.
 */
export type Labels = Record<string, string>;

/**
 * Подпись: локаль ИНТЕРФЕЙСА, затем язык ДАННЫХ, затем запасная строка.
 *
 * Осей две, и обе тут по делу. Подпись поля, имя таблицы и имя вкладки —
 * это надписи интерфейса, и переключение языка интерфейса обязано их
 * менять: так ведёт себя старая админка, которая читает эти же ключи
 * как `attributes[label_${i18n.language}]`. Но лежат они под кодами
 * языков ПРОЕКТА, а те с ru/en/uz совпадают не всегда — у проекта
 * на en+cyr ключа `label_ru` нет вовсе. Тогда берётся язык данных,
 * и подпись остаётся подписью, а не откатывается к слагу.
 *
 * Значение мультиязычного ПОЛЯ по-прежнему выбирает только язык данных:
 * это данные, а не надпись, и локаль интерфейса на них не влияет.
 *
 * Третья ступень нужна отдельно: базовой подписи может не быть вовсе
 * (у вариантов STATUS её нет) — тогда показываем сохранённое значение,
 * а не пустоту.
 */
export function localized(labels: Labels, language: string, fallback: string): string {
  return labels[i18n.language]?.trim() || labels[language]?.trim() || fallback;
}

/** Группы вариантов STATUS. Бэкенд хранит их тремя отдельными списками. */
export const STATUS_GROUPS = ["todo", "progress", "complete"] as const;
export type StatusGroup = (typeof STATUS_GROUPS)[number];

/**
 * Вариант выбора у STATUS и MULTISELECT.
 *
 * Приведён к одной форме сознательно: в сыром виде это два разных формата.
 * У MULTISELECT сохранённое в строке значение лежит в `slug`, а `value`
 * занят подписью на базовом языке; у STATUS всё наоборот — есть только
 * `value`, и в нём именно сохраняемое значение. Старый ucode искал
 * вариант по `option.value` для обоих типов, поэтому у MULTISELECT
 * не находил никогда: ячейка теряла и цвет, и перевод.
 */
export type FieldOption = {
  /** То, что лежит в строке. Единственный ключ поиска. */
  value: string;
  /** Подпись без языка. У STATUS её нет — тогда пустая строка. */
  label: string;
  labels: Labels;
  /** HEX из данных. Наружу отдаётся как есть, в токен переводит UI. */
  color: string | null;
  icon: string | null;
  /** Только у STATUS. */
  group: StatusGroup | null;
};

/**
 * Типы, по которым бэкенд действительно умеет искать: общий поиск
 * собирается как `a.<колонка> ~* $1`, и в него попадают только поля,
 * чей тип ложится в VARCHAR (helper.FIELD_TYPES в object_builder).
 * NUMBER и DATE в этот список не входят — регулярное выражение
 * по числовой колонке ронять запрос будет молча, пустым результатом.
 */
export const SEARCH_TYPES = new Set([
  "SINGLE_LINE",
  "MULTI_LINE",
  "EMAIL",
  "PHONE",
  "INTERNATION_PHONE",
  "PICK_LIST",
  "UUID",
  "INCREMENT_ID",
  "RANDOM_NUMBERS",
  "CODABAR",
  "FORMULA_FRONTEND",
  "MAP",
  "JSON",
  "CODE",
]);

export type FieldValidation = {
  pattern: RegExp;
  /** Текст админа. Пусто — своего текста он не задал, скажем общими словами. */
  message: string;
};

export type Field = {
  id: string;
  slug: string;
  label: string;
  labels: Labels;
  type: string;
  /**
   * Только у LOOKUP и LOOKUPS: id связи, а не поля.
   *
   * View перечисляет колонки идентификаторами, и для полей-связей это
   * id связи (`relation_field`), а не id самого поля. Поэтому колонка
   * ищется по двум ключам сразу — см. features/view/model/columns.
   */
  relationId: string | null;
  /**
   * Варианты выбора. Пусто у всех типов, кроме STATUS и MULTISELECT.
   * Индекс по value, потому что ищут по нему на каждой ячейке.
   */
  options: Map<string, FieldOption>;
  /**
   * Мультиязычное поле — см. [[Multilanguage Field]] в CONTEXT.md.
   *
   * Ловушка: это НЕ одно поле с картой значений по языкам. Бэкенд
   * заводит по колонке на язык, и слаг каждой оканчивается кодом языка
   * данных: `title_en`, `title_cyr`. В схеме они приходят отдельными
   * Field'ами, и без сборки обратно карточка показывает три строки
   * «Название» вместо одной с переключателем языка.
   *
   * Собирает их model/multilanguage.
   */
  multilanguage: boolean;
  /** Красить ли варианты. Выключено — чип нейтральный, цвет игнорируется. */
  hasColor: boolean;
  /**
   * Заполнение обязательно. Колонка `required` в таблице field, а не
   * ключ в attributes: бэкенд её и проверяет при вставке.
   */
  required: boolean;
  /**
   * Проверка вводимого значения. Собрана из двух ключей attributes —
   * `validation` (текст регулярного выражения) и `validation_message`.
   * null — проверять нечем: ключа нет, он пуст или выражение битое.
   *
   * Компилируется здесь, один раз на поле, а не в ячейке: битое
   * выражение из настроек не должно ронять рендер строки, а собирать
   * RegExp на каждое нажатие клавиши незачем.
   */
  validation: FieldValidation | null;
  /**
   * Разрешено ли менять значение. Два запрета от бэкенда: `disabled`
   * ставит админ в настройках поля, `field_permission.edit_permission` —
   * право роли.
   *
   * Право роли из ЭТОЙ ручки не приходит: /v2/fields отдаёт схему
   * одинаковой для всех. Оно живёт в раскладке карточки и накладывается
   * поверх — см. features/item/model/layout, `applyRights`. Здесь
   * читается тот же ключ на случай, когда поле пришло оттуда, где он
   * всё-таки есть.
   *
   * Отдельно от типа: вычисляемые поля (INCREMENT_ID, FORMULA) закрыты
   * всегда, и это знает features/item, а не схема.
   */
  editable: boolean;
  /** Свободный мешок бэкенда: формат, настройки формулы, значение по умолчанию. */
  attributes: Record<string, unknown>;
  /**
   * Ответ сервера как есть. Нужен ровно для одного — правки поля.
   *
   * PUT /v2/fields перезаписывает запись ЦЕЛИКОМ (field.go: `UPDATE
   * "field" SET` по всем колонкам сразу), и всё, чего в теле не было,
   * обнуляется: `required`, `unique`, `default`, автозаполнение.
   * Моделировать десяток чужих настроек ради того, чтобы вернуть их
   * нетронутыми, незачем — отправляем обратно то, что пришло, меняя
   * только то, что правил человек.
   */
  raw: Record<string, unknown>;
};

/** Связь между таблицами. Нужна, чтобы показать в ячейке не uuid, а значение. */
export type Relation = {
  id: string;
  /** Many2One, One2Many, Many2Many. */
  type: string;
  /** Слаг таблицы, куда ведёт связь. */
  toSlug: string;
  /**
   * Её подпись и подписи по языкам данных.
   *
   * Нужны там, где у самой связи имени не задали: колонка тогда
   * называется `<чужая таблица>_id`, и показывать этот слаг человеку
   * нечестно — он про устройство базы, а не про то, что в колонке.
   * Обратную сторону связи бэкенд заводит сам и без имени, так что
   * это не редкий случай.
   */
  toLabel: string;
  toLabels: Labels;
  /**
   * Имя самой связи, заданное админом (`view.name` привязанного view).
   *
   * Оно точнее имени чужой таблицы: у двух связей на одну таблицу
   * — «склад отправитель» и «склад получатель» — имя таблицы одно
   * на двоих, и вкладки различаются только этим. Пусто — имени
   * не задавали.
   */
  title: string;
  /**
   * Колонка-связь В ЭТОЙ таблице: у Many2One это `<чужая таблица>_id`.
   * Рядом с ней в строке приходит связанная запись — `<fieldFrom>_data`,
   * из неё и берёт значение автозаполнение (см. FieldDraft.autofillTable).
   *
   * Пусто, когда связь ведёт К нам: идентификатор тогда лежит в чужой
   * строке, и в нашей брать нечего.
   */
  fieldFrom: string;
  /**
   * Куда смотрит связь ОТ ЭТОЙ таблицы:
   *
   *   outgoing — колонка-ссылка у нас, в ней guid чужой строки;
   *   incoming — колонка-ссылка у чужой таблицы, в ней наш guid.
   *
   * Считается по слагу, а не по `table_from`: связь лежит в базе один
   * раз, и обе стороны читают одну и ту же строку.
   */
  direction: "incoming" | "outgoing";
  /**
   * Имя колонки-ссылки. Она всегда в `table_from` и у Many2One
   * называется `<слаг table_to>_id` (pkg/helper/relation.go).
   *
   * Берётся из ответа, а не собирается из слагов: имя бывает своим
   * (Many2Dynamic), а вторая связь на ту же таблицу получает колонку
   * с суффиксом. Собранное имя в обоих случаях промахивается мимо
   * настоящей колонки, и отбор по нему возвращает пусто.
   */
  linkField: string;
  /**
   * Какие поля показывать вместо uuid. Слаги полей целевой таблицы.
   *
   * Может быть пустым или указывать на поля исходной таблицы — так
   * выглядит ненастроенная связь. Тогда показать нечего, и ячейка
   * остаётся пустой: угадывать поле по имени («title», «name») нельзя,
   * это ровно тот `a || b || c.d`, из-за которого в старом ucode
   * одно и то же значение читалось четырьмя разными способами.
   */
  viewFieldSlugs: string[];
  /**
   * Те же поля показа, но идентификаторами: PUT /v2/relations ждёт
   * `view_fields` списком id, а ячейка читает значения по слагам.
   * Одно и то же под двумя ключами — разворачивается один раз, здесь.
   */
  viewFieldIds: string[];
  /**
   * Связь, как её отдал бэкенд. Нужна для правки: PUT перезаписывает
   * строку целиком, и тело, собранное заново, стёрло бы полтора десятка
   * настроек, которых мы не показываем (auto_filters, cascading,
   * summaries, action_relations).
   */
  raw: Record<string, unknown>;
};

export type TableSchema = {
  fields: Field[];
  relations: Relation[];
};

/** Пустая схема — чтобы вызывающий код не разбирал undefined. */
export const EMPTY_SCHEMA: TableSchema = { fields: [], relations: [] };
